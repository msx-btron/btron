#!/usr/bin/env python3
"""
mk_picocalc_fs.py — Pack real B-System repository files into a Flash XIP
B-System ROMFS image ("BROM" v1) for PicoCalc & SegUI builds.

Zero hardcoded mock strings in C: every file in /SYS Cabinet (NORTIA.TAD,
OSAL_BOOK.TAD, HEART_SUTRA.TAD, PICO.TXT) is read verbatim from the repo
into the bundled image we boot from.
"""

import os
import struct
import sys

MAGIC = b"BROM"
VERSION = 1

# (volume_name, repo_relative_path, flags: bit0=is_tad, bit1=editable_copy)
MANIFEST = [
    ("NORTIA.TAD",      "assets/texts/BTRON3_Report.txt",       0x03),
    ("OSAL_BOOK.TAD",   "tad_bin/osal/index.tad",               0x01),
    ("SMON_LAM.TAD",    "tad_bin/osal/smon_lam.tad",            0x01),
    ("KHRUS.TAD",       "tad_bin/osal/khrus.tad",               0x01),
    ("DGE_BSNGO.TAD",   "tad_bin/osal/dge_bsngo.tad",           0x01),
    ("HEART_SUTRA.TAD", "assets/texts/Heart_Sutra_Tibetan.txt", 0x01),
    ("PICO.TXT",        "doc/txt/PICO.txt",                     0x00),
]


def build_image(repo_root: str, out_img: str, out_hdr: str) -> None:
    entries = []
    for name, rel_path, flags in MANIFEST:
        full_path = os.path.join(repo_root, rel_path)
        if not os.path.isfile(full_path):
            sys.exit(f"mk_picocalc_fs.py: missing source file: {full_path}")
        with open(full_path, "rb") as f:
            payload = f.read()
        entries.append((name, rel_path, flags, payload))

    # Header: 16-byte superblock + 36-byte dirent * N
    super_sz = 16
    dirent_sz = 36
    data_off = super_sz + dirent_sz * len(entries)
    # Align data payloads to 4 bytes
    data_off = (data_off + 3) & ~3

    offsets = []
    cur = data_off
    for _, _, _, payload in entries:
        offsets.append(cur)
        cur += len(payload) + 1  # +1 NUL terminator for safe C text access
        cur = (cur + 3) & ~3

    total_size = cur
    buf = bytearray(total_size)

    struct.pack_into("<4sIII", buf, 0, MAGIC, VERSION, len(entries), total_size)

    for idx, (name, _, flags, payload) in enumerate(entries):
        name_b = name.encode("ascii")[:23]
        name_padded = name_b + b"\x00" * (24 - len(name_b))
        struct.pack_into(
            "<24sIII",
            buf,
            super_sz + idx * dirent_sz,
            name_padded,
            offsets[idx],
            len(payload),
            flags,
        )
        buf[offsets[idx] : offsets[idx] + len(payload)] = payload
        buf[offsets[idx] + len(payload)] = 0

    os.makedirs(os.path.dirname(out_img), exist_ok=True)
    with open(out_img, "wb") as f:
        f.write(buf)

    os.makedirs(os.path.dirname(out_hdr), exist_ok=True)
    with open(out_hdr, "w", encoding="utf-8") as f:
        f.write("/* Auto-generated by scripts/mk_picocalc_fs.py — DO NOT EDIT */\n")
        f.write("#ifndef _BTRON_PICOCALC_FS_IMAGE_H_\n")
        f.write("#define _BTRON_PICOCALC_FS_IMAGE_H_\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write("/* Bundled files:\n")
        for (name, rel_path, _, payload) in entries:
            f.write(f" *   /SYS/{name:<16s} <- {rel_path} ({len(payload)} bytes)\n")
        f.write(" */\n")
        f.write(f"static const uint8_t btron_picocalc_fs_img[{len(buf)}] = {{\n")
        for i in range(0, len(buf), 16):
            chunk = ", ".join(f"0x{b:02x}" for b in buf[i : i + 16])
            f.write(f"    {chunk},\n")
        f.write("};\n\n#endif /* _BTRON_PICOCALC_FS_IMAGE_H_ */\n")

    print(
        f"[MKFS] Packed {len(entries)} real files -> {out_img} "
        f"({len(buf)} bytes Flash XIP, 0 B SRAM)"
    )


if __name__ == "__main__":
    root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    out_img = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "build", "picocalc_fs.img")
    out_hdr = sys.argv[2] if len(sys.argv) > 2 else os.path.join(root, "src", "apps", "cabinet", "picocalc_fs_image.h")
    build_image(root, out_img, out_hdr)
