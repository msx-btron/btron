/*
 * dp_pico.c — Banded 320x16 RGB565 Display Primitives (GDEV) for PicoCalc
 *
 * Implements the exact 3 graphics/text primitives required by SegUI:
 *   - fill_rec(GDEV *, const RECT *, COLOR)
 *   - drw_tc_string(GDEV *, H, H, const char *, COLOR, COLOR)
 *   - tc_calc_string_width(const char *, int)
 *
 * Uses double-buffered 320x16 big-endian RGB565 strips (20 KiB total SRAM)
 * overlapped with SPI1 DMA Channel 0 transfers (st7365p_flush_band_dma).
 * All glyph bitmaps live `const` in Flash XIP (0 bytes SRAM).
 *
 * Copyright 2026 Synrc Research Center. MIT License.
 */

